-- backend/schema.sql
-- ClashFree: Constraint-Based Timetable & Academic Resource Management System
-- Run this script in the Supabase SQL Editor to initialize or upgrade the database.

-- 1. Departments Table
CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Academic Structure Table
CREATE TABLE IF NOT EXISTS academic_structure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code TEXT NOT NULL,
    degree TEXT NOT NULL DEFAULT 'B.Tech',
    year TEXT NOT NULL DEFAULT 'Second Year',
    semester TEXT NOT NULL DEFAULT 'Semester III',
    academic_year TEXT NOT NULL DEFAULT '2026-2027',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Divisions Table (Upgrades/replaces basic sections)
CREATE TABLE IF NOT EXISTS divisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code TEXT NOT NULL DEFAULT 'CSE',
    degree TEXT NOT NULL DEFAULT 'B.Tech',
    year TEXT NOT NULL DEFAULT 'Second Year',
    semester TEXT NOT NULL DEFAULT 'Semester III',
    name TEXT NOT NULL,
    strength INT NOT NULL DEFAULT 60,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Batches Table
CREATE TABLE IF NOT EXISTS batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_name TEXT NOT NULL,
    name TEXT NOT NULL,
    strength INT NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Existing Sections Table (kept for backward compatibility)
CREATE TABLE IF NOT EXISTS sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    strength INT NOT NULL DEFAULT 60,
    department TEXT DEFAULT 'CSE',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Rooms / Resources Table
CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('Classroom', 'Lab')),
    capacity INT NOT NULL,
    department TEXT NOT NULL DEFAULT 'CSE',
    lab_type TEXT DEFAULT 'Computer Lab',
    num_pcs INT DEFAULT 0,
    equipment TEXT DEFAULT 'Projector, LAN',
    is_reserved BOOLEAN NOT NULL DEFAULT FALSE,
    reservation_reason TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Alter rooms if columns are missing
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS department TEXT DEFAULT 'CSE';
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS lab_type TEXT DEFAULT 'Computer Lab';
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS num_pcs INT DEFAULT 0;
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS equipment TEXT DEFAULT 'Projector, LAN';
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS is_reserved BOOLEAN DEFAULT FALSE;
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS reservation_reason TEXT DEFAULT '';

-- 7. Resource Configurations (HOD Reservation Requirement)
CREATE TABLE IF NOT EXISTS resource_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department TEXT NOT NULL UNIQUE DEFAULT 'CSE',
    reserved_classrooms_count INT NOT NULL DEFAULT 1,
    reserved_labs_count INT NOT NULL DEFAULT 1,
    student_pc_ratio TEXT NOT NULL DEFAULT '1:1',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Faculty Table
CREATE TABLE IF NOT EXISTS faculty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT NOT NULL,
    designation TEXT NOT NULL DEFAULT 'Assistant Professor',
    department TEXT NOT NULL DEFAULT 'CSE',
    subjects TEXT[] NOT NULL DEFAULT '{}',
    available_from TEXT NOT NULL DEFAULT '09:00',
    available_to TEXT NOT NULL DEFAULT '17:00',
    preferred_time TEXT NOT NULL DEFAULT 'Any',
    blocked_slots TEXT[] NOT NULL DEFAULT '{}',
    max_load INT NOT NULL DEFAULT 20,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE faculty ADD COLUMN IF NOT EXISTS designation TEXT DEFAULT 'Assistant Professor';
ALTER TABLE faculty ADD COLUMN IF NOT EXISTS department TEXT DEFAULT 'CSE';
ALTER TABLE faculty ADD COLUMN IF NOT EXISTS blocked_slots TEXT[] DEFAULT '{}';

-- 9. Subjects Table
CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT,
    department TEXT NOT NULL DEFAULT 'CSE',
    year TEXT DEFAULT 'Second Year',
    semester TEXT DEFAULT 'Semester III',
    lectures_per_week INT NOT NULL DEFAULT 3,
    labs_per_week INT NOT NULL DEFAULT 0,
    requires_lab BOOLEAN NOT NULL DEFAULT FALSE,
    lab_type TEXT DEFAULT 'Computer Lab',
    student_pc_ratio NUMERIC DEFAULT 1.0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE subjects ADD COLUMN IF NOT EXISTS department TEXT DEFAULT 'CSE';
ALTER TABLE subjects ADD COLUMN IF NOT EXISTS year TEXT DEFAULT 'Second Year';
ALTER TABLE subjects ADD COLUMN IF NOT EXISTS semester TEXT DEFAULT 'Semester III';
ALTER TABLE subjects ADD COLUMN IF NOT EXISTS lab_type TEXT DEFAULT 'Computer Lab';
ALTER TABLE subjects ADD COLUMN IF NOT EXISTS student_pc_ratio NUMERIC DEFAULT 1.0;

-- 10. Time Slots Table
CREATE TABLE IF NOT EXISTS time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('TEACHING', 'SHORT_BREAK', 'LUNCH', 'NON_TEACHING')),
    is_morning BOOLEAN NOT NULL DEFAULT FALSE,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    order_index INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Timetable Versions Table
CREATE TABLE IF NOT EXISTS timetable_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_number INT NOT NULL DEFAULT 1,
    name TEXT NOT NULL,
    academic_year TEXT NOT NULL DEFAULT '2026-2027',
    semester TEXT NOT NULL DEFAULT 'Semester III',
    department TEXT NOT NULL DEFAULT 'CSE',
    description TEXT DEFAULT 'Initial timetable',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by TEXT DEFAULT 'HOD',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Timetable Table (Master Timetable source of truth)
CREATE TABLE IF NOT EXISTS timetable (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT DEFAULT 1,
    day TEXT NOT NULL,
    day_order INT NOT NULL,
    period TEXT NOT NULL,
    is_morning BOOLEAN NOT NULL DEFAULT FALSE,
    department TEXT NOT NULL DEFAULT 'CSE',
    section TEXT NOT NULL,
    batch TEXT DEFAULT NULL,
    subject TEXT NOT NULL,
    faculty_code TEXT NOT NULL,
    faculty_name TEXT,
    room TEXT NOT NULL,
    is_lab BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE timetable ADD COLUMN IF NOT EXISTS version_id BIGINT DEFAULT 1;
ALTER TABLE timetable ADD COLUMN IF NOT EXISTS department TEXT DEFAULT 'CSE';
ALTER TABLE timetable ADD COLUMN IF NOT EXISTS batch TEXT DEFAULT NULL;

-- 13. Resource Sharing Requests Table
CREATE TABLE IF NOT EXISTS resource_sharing_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_name TEXT NOT NULL,
    day TEXT NOT NULL,
    period TEXT NOT NULL,
    owner_department TEXT NOT NULL,
    requesting_department TEXT NOT NULL,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    requested_by TEXT DEFAULT 'Coordinator',
    reviewed_by TEXT DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

