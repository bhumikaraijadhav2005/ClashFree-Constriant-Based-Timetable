-- Helper functions for RLS session evaluation
CREATE OR REPLACE FUNCTION auth_user_role() RETURNS TEXT AS $$
    SELECT role FROM public.user_roles WHERE user_id = auth.uid()::text LIMIT 1;
$$ LANGUAGE SQL STABLE SECURITY DEFINER;

CREATE OR REPLACE FUNCTION auth_user_department() RETURNS TEXT AS $$
    SELECT department_code FROM public.user_roles WHERE user_id = auth.uid()::text AND department_code IS NOT NULL LIMIT 1;
$$ LANGUAGE SQL STABLE SECURITY DEFINER;

CREATE OR REPLACE FUNCTION auth_user_college_id() RETURNS BIGINT AS $$
    SELECT college_id FROM public.user_roles WHERE user_id = auth.uid()::text AND college_id IS NOT NULL LIMIT 1;
$$ LANGUAGE SQL STABLE SECURITY DEFINER;

-- Policies for user_profiles:
-- Users can view their own profile; Super Admins can view and manage all profiles
DROP POLICY IF EXISTS "Users can view own profile" ON user_profiles;
CREATE POLICY "Users can view own profile" ON user_profiles
    FOR SELECT USING (id = auth.uid()::text OR auth_user_role() = 'SUPER_ADMIN');

-- Policies for user_roles:
-- Super Admin can manage all roles; HOD can manage TIMETABLE_CREATOR in their own department
DROP POLICY IF EXISTS "Role visibility policy" ON user_roles;
CREATE POLICY "Role visibility policy" ON user_roles
    FOR SELECT USING (
        user_id = auth.uid()::text 
        OR auth_user_role() IN ('SUPER_ADMIN', 'INSTITUTIONAL_VIEWER')
        OR (auth_user_role() = 'HOD' AND department_code = auth_user_department())
    );

DROP POLICY IF EXISTS "Role management policy" ON user_roles;
CREATE POLICY "Role management policy" ON user_roles
    FOR ALL USING (
        auth_user_role() = 'SUPER_ADMIN'
        OR (auth_user_role() = 'HOD' AND role = 'TIMETABLE_CREATOR' AND department_code = auth_user_department())
    );

-- Policies for audit_logs:
-- Super Admin views all logs; HOD views departmental logs; no one can tamper with past logs
DROP POLICY IF EXISTS "Audit log read policy" ON audit_logs;
CREATE POLICY "Audit log read policy" ON audit_logs
    FOR SELECT USING (
        auth_user_role() = 'SUPER_ADMIN'
        OR (auth_user_role() IN ('HOD', 'INSTITUTIONAL_VIEWER') AND (department_code = auth_user_department() OR department_code IS NULL))
    );

DROP POLICY IF EXISTS "Audit log insert policy" ON audit_logs;
CREATE POLICY "Audit log insert policy" ON audit_logs
    FOR INSERT WITH CHECK (TRUE);

-- Policies for timetable_versions:
-- Viewable by college members; editable by Super Admin, HOD, and Timetable Creator
DROP POLICY IF EXISTS "Timetable version view policy" ON timetable_versions;
CREATE POLICY "Timetable version view policy" ON timetable_versions
    FOR SELECT USING (
        auth_user_role() = 'SUPER_ADMIN'
        OR college_id = auth_user_college_id()
        OR department = auth_user_department()
    );

DROP POLICY IF EXISTS "Timetable version modification policy" ON timetable_versions;
CREATE POLICY "Timetable version modification policy" ON timetable_versions
    FOR ALL USING (
        auth_user_role() = 'SUPER_ADMIN'
        OR (auth_user_role() IN ('HOD', 'TIMETABLE_CREATOR') AND department = auth_user_department())
    );

